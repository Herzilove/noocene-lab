import {test,expect} from '@playwright/test';
test('companion, reality lens and a voluntary time capsule form a revisitable loop',async({page})=>{
 test.setTimeout(60000);
 await page.setViewportSize({width:390,height:844});
 await page.goto('/innerspace?mode=solo');
 await page.getByRole('button',{name:'Get a hint from your companion'}).click();
 await expect(page.getByText('Start with one moment, not your whole day.',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'Your moment',exact:true}).fill('Fictional: a friend has not replied.');
 await page.getByRole('button',{name:/^Next/}).click();
 await page.getByRole('textbox',{name:'Your first thought',exact:true}).fill('They are annoyed with me.');
 await page.getByRole('button',{name:/^Next/}).click();
 await page.getByRole('button',{name:'What happened',exact:true}).click();
 await expect(page.locator('.reality-content')).toContainText('Fictional: a friend has not replied.');
 await page.getByRole('button',{name:'My interpretation',exact:true}).click();
 await expect(page.locator('.reality-content')).toContainText('They are annoyed with me.');
 await page.screenshot({path:'test-results/reality-lens-mobile.png',fullPage:true,animations:'disabled'});
 await page.getByRole('textbox',{name:'Your new angle',exact:true}).fill('They may be busy.');
 await page.getByRole('button',{name:/Show my discovery/}).click();
 await expect(page.getByText('3 steps explored',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/Ask an open question/}).click();
 await page.getByText('Make a time capsule',{exact:true}).click();
 await page.getByRole('textbox',{name:'My prediction',exact:true}).fill('I expect we will talk tomorrow.');
 expect(await page.evaluate(()=>localStorage.getItem('noocene:garden:v1'))).toBeNull();
 await page.getByRole('button',{name:/Keep this discovery/}).click();
 await page.getByRole('button',{name:'Yes, save on this device',exact:true}).click();
 await page.getByRole('link',{name:/Open my garden/}).click();
 await page.reload();
 await page.getByRole('button',{name:/DISCOVERY 01/}).click();
 await expect(page.getByText('I expect we will talk tomorrow.',{exact:true})).toBeVisible();
 await page.getByRole('textbox',{name:'What actually happened?',exact:true}).fill('We talked the next morning.');
 await page.getByRole('button',{name:'Save my check-in',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Check-in saved. Your discovery has a new chapter.');
 await page.reload();
 await page.getByRole('button',{name:/DISCOVERY 01/}).click();
 await expect(page.getByRole('textbox',{name:'What actually happened?',exact:true})).toHaveValue('We talked the next morning.');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
